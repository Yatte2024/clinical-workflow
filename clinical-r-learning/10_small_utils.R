# ---------------------------------------------------------------------------
# round_any(): plyr::round_any 的轻量替代——四舍五入到某个倍数
#
# 口径 / 假设：
#   - f 默认 round；传 ceiling / floor 可做"向上/向下取整到倍数"。
#   - 例：round_any(7, 5) = 5；round_any(7, 5, ceiling) = 10。
#   - 存在浮点误差风险（如 accuracy = 0.1 时），必要时对结果再 round 一次。
# ---------------------------------------------------------------------------
round_any <- function(x, accuracy, f = round) {
  f(x / accuracy) * accuracy
}


# ---------------------------------------------------------------------------
# all_na(): 判断向量是否全为 NA
#
# 口径 / 假设：
#   - 常用于分组后判断"某受试者某指标整组缺失"（配合 group_by + filter）。
#   - 空向量返回 TRUE（all(logical(0)) 的语义），注意边界。
# ---------------------------------------------------------------------------
all_na <- function(x) {
  all(is.na(x))
}


# ---------------------------------------------------------------------------
# clean_column_text(): 文本标准化（大写 + 去标点 + 压缩空白）
#
# 手段：toupper → 把非字母数字空格的字符替换成空格 → trim → 多个空白压成一个。
#
# 口径 / 假设：
#   - 用于把 EPOCH/DSREFID/study_phase 等自由文本对齐后再做匹配，消除标点/
#     大小写/多空格带来的不一致。
#   - 会丢掉所有标点（含连字符、括号），若这些标点在你的场景里有意义（如剂量
#     "10-20"），不要用它。
# ---------------------------------------------------------------------------
clean_column_text <- function(x) {
  trimws(gsub("[^[:alnum:] ]", " ", toupper(as.character(x)))) |>
    gsub("\\s+", " ", x = _)
}


# ---------------------------------------------------------------------------
# remove_hyphen(): 去掉字符串里所有连字符
#
# 口径 / 假设：极简工具，gsub("-", "", ...)。常用于把带连字符的 ID 归一化后比对。
# ---------------------------------------------------------------------------
remove_hyphen <- function(inputvalue) {
  gsub(pattern = "-", replacement = "", inputvalue)
}


# ---------------------------------------------------------------------------
# extract_num_after_N(): 从形如 "Group A (N=123)" 的标签里抠出 N 值
#
# 手段：正则 "N\\s*=\\s*(\\d+)" 抓第一个 N= 后的整数。
#
# 口径 / 假设：
#   - 返回 integer 向量，与输入等长；抓不到返回 NA。
#   - 只抓第一个匹配；一个标签里有多个 N= 时其余忽略。
#   - 大小写敏感（只认大写 N）。
# ---------------------------------------------------------------------------
extract_num_after_N <- function(x) {
  m <- stringr::str_match(x, "N\\s*=\\s*(\\d+)")
  as.integer(m[, 2])
}


# ---------------------------------------------------------------------------
# wrap_levels(): 把因子水平名按宽度折行（画图/表格排版用）
#
# 手段：对每个 level 用 strwrap 按 width 折行，用 "\n" 连接后写回 levels()。
#
# 口径 / 假设：
#   - width 为 NA/NULL 时原样返回（方便在参数化流程里"传 NA 即不折行"）。
#   - 改的是 levels 的显示文本，不改数据本身的分组。
#   - 只对因子有意义；传字符向量 levels() 为 NULL，会得到 NULL levels。
# ---------------------------------------------------------------------------
wrap_levels <- function(x, width = 12) {
  if (is.na(width) | is.null(width)) {
    return(x)
  }
  new <- vapply(levels(x), function(lv) paste(strwrap(lv, width = width), collapse = "\n"), character(1))
  levels(x) <- new
  x
}


# ---------------------------------------------------------------------------
# rm_white_spaces(): 把整表的"纯空白字符串"统一成 NA（并保持因子）
#
# 手段：先把因子转字符 → 把只含空白（^\s*$）的值置为 NA → 再转回因子。
#
# 口径 / 假设：
#   - 这是 09 里 overwrite_baseline_flag() 等函数的前置清洗步骤，单独放这里
#     供复用（原包散落在多处）。
#   - 会把所有字符列重新变成因子——若你下游依赖字符类型，注意这个副作用。
#   - 只处理"纯空白"，不 trim 前后空格；要 trim 请另配 trimws。
# ---------------------------------------------------------------------------
rm_white_spaces <- function(data) {
  checkmate::assert_data_frame(data, min.rows = 1)
  data |>
    dplyr::mutate(dplyr::across(dplyr::where(is.factor), as.character)) |>
    dplyr::mutate(dplyr::across(dplyr::where(is.character), ~ ifelse(grepl("^\\s*$", .), NA, .))) |>
    dplyr::mutate(dplyr::across(dplyr::where(is.character), as.factor))
}
